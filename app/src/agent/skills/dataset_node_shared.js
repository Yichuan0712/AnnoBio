function toCleanString(value) {
  return String(value == null ? '' : value).trim();
}

function normalizeBoolean(value, fallback = false) {
  return typeof value === 'boolean' ? value : fallback;
}

function normalizeStringArray(value) {
  return Array.isArray(value)
    ? value.map((item) => String(item == null ? '' : item).trim())
    : [];
}

export function buildSyntheticDatasetSpec(args = {}) {
  const name = toCleanString(args?.name) || 'Synthetic Dataset';
  const notes = toCleanString(args?.notes || args?.note) || 'Synthetic dataset generated by Agent for prototyping.';
  const headers = normalizeStringArray(args?.headers).filter(Boolean);
  const rows = (Array.isArray(args?.rows) ? args.rows : [])
    .map((row) => (Array.isArray(row) ? row.map((cell) => String(cell == null ? '' : cell)) : []))
    .filter((row) => row.length > 0);
  const left = Number.isFinite(Number(args?.left)) ? Number(args.left) : null;
  const top = Number.isFinite(Number(args?.top)) ? Number(args.top) : null;
  const ensureUniqueName = normalizeBoolean(args?.ensure_unique_name, true);

  if (headers.length === 0) {
    throw new Error('At least one dataset header is required.');
  }
  if (rows.length === 0) {
    throw new Error('At least one dataset row is required.');
  }
  for (const row of rows) {
    if (row.length !== headers.length) {
      throw new Error('Each dataset row must have the same number of cells as headers.');
    }
  }

  return {
    name,
    notes,
    headers,
    rows,
    ...(left != null ? { left } : {}),
    ...(top != null ? { top } : {}),
    ensureUniqueName,
  };
}

export function summarizeSyntheticDatasetSpec(spec = {}) {
  const headers = Array.isArray(spec?.headers) ? spec.headers : [];
  const rows = Array.isArray(spec?.rows) ? spec.rows : [];
  return {
    name: toCleanString(spec?.name) || 'Synthetic Dataset',
    notes: String(spec?.notes || ''),
    headerCount: headers.length,
    rowCount: rows.length,
    headers,
  };
}
