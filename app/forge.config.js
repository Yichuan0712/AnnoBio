const path = require('path');
const fs = require('fs');
const { execFileSync } = require('child_process');
const { FusesPlugin } = require('@electron-forge/plugin-fuses');
const { FuseV1Options, FuseVersion } = require('@electron/fuses');

// `backend` is a Python env with tens of thousands of small files (numpy, onnxruntime,
// pandas, etc.). Node's fs.cpSync copies one file at a time - painfully slow on Windows,
// where every new file also gets scanned synchronously by Defender's real-time protection.
// robocopy is multi-threaded and built into Windows, so use it there; fall back to
// fs.cpSync elsewhere. __pycache__ is regenerated by Python on first import, so skip it.
function copyBackend(src, dest) {
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  if (process.platform === 'win32') {
    try {
      execFileSync('robocopy', [
        src, dest, '/E', '/MT:16', '/XD', '__pycache__',
        '/NFL', '/NDL', '/NJH', '/NJS', '/NC', '/NS', '/NP',
      ]);
    } catch (err) {
      // robocopy exit codes 0-7 mean success (files copied/skipped/mismatched);
      // only 8+ is a real failure.
      if (typeof err.status !== 'number' || err.status >= 8) {
        throw err;
      }
    }
  } else {
    fs.cpSync(src, dest, { recursive: true, filter: (p) => !p.includes(`${path.sep}__pycache__`) });
  }
}

module.exports = {
  packagerConfig: {
    asar: true,
    icon: path.join(__dirname, 'assets', 'icon'),
    // electron-packager names the packaged output dir `${name}-${platform}-${arch}`,
    // and infers `name` from package.json's `productName` ("AnnoBio") when this
    // isn't set - producing `out/AnnoBio-win32-x64`. The `dist`/`dist:mac` npm
    // scripts and electron-builder.yml's `--pd` flag hardcode `out/app-<platform>-<arch>`,
    // so without this override electron-builder was always pointed at a directory that
    // never existed - the real root cause of every NSIS/dmg build failure so far.
    name: 'app',
  },
  rebuildConfig: {},
  hooks: {
    postPackage: async (_config, context) => {
      const backendSrc = path.join(__dirname, '..', 'backend');
      const paths = context.outputPaths || [];
      for (const outputPath of paths) {
        if (fs.existsSync(backendSrc)) {
          const backendDest = path.join(outputPath, 'resources', 'backend');
          copyBackend(backendSrc, backendDest);
        }
        const pkgPath = path.join(__dirname, 'package.json');
        if (fs.existsSync(pkgPath)) {
          fs.copyFileSync(pkgPath, path.join(outputPath, 'package.json'));
        }
      }
    },
  },
  plugins: [
    {
      name: '@electron-forge/plugin-vite',
      config: {
        // `build` can specify multiple entry builds, which can be Main process, Preload scripts, Worker process, etc.
        // If you are familiar with Vite configuration, it will look really familiar.
        build: [
          {
            // `entry` is just an alias for `build.lib.entry` in the corresponding file of `config`.
            entry: 'src/main.js',
            config: 'vite.main.config.mjs',
            target: 'main',
          },
          {
            entry: 'src/preload.js',
            config: 'vite.preload.config.mjs',
            target: 'preload',
          },
        ],
        renderer: [
          {
            name: 'main_window',
            config: 'vite.renderer.config.mjs',
          },
        ],
      },
    },
    // Fuses are used to enable/disable various Electron functionality
    // at package time, before code signing the application
    new FusesPlugin({
      version: FuseVersion.V1,
      [FuseV1Options.RunAsNode]: false,
      [FuseV1Options.EnableCookieEncryption]: true,
      [FuseV1Options.EnableNodeOptionsEnvironmentVariable]: false,
      [FuseV1Options.EnableNodeCliInspectArguments]: false,
      [FuseV1Options.EnableEmbeddedAsarIntegrityValidation]: true,
      [FuseV1Options.OnlyLoadAppFromAsar]: true,
    }),
  ],
};
