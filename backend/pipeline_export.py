    """Write scalar values directly and serialize nested structured values as JSON."""
    path.parent.mkdir(parents=True, exist_ok=True)
    output = frame.map(_excel_value) if hasattr(frame, "map") else frame.applymap(_excel_value)
    output.to_excel(path, index=False, sheet_name="Output")


