"""Build standalone Python projects from a selected AnnoBio pipeline route.

The generated archive deliberately contains code and data contracts only. Dataset rows, binary
assets, cached results, API keys, and canvas layout are never included.
"""

from __future__ import annotations

import keyword
import pprint
import re
import textwrap
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Any


FORMAT_NAME = "annobio.pipeline"
FORMAT_VERSION = 1


class PipelineExportError(ValueError):
    """A user-correctable problem in the selected route or node configuration."""


@dataclass(frozen=True)
class ExportedFile:
    path: str
    content: str


@dataclass(frozen=True)
class ExportMetadata:
    """Trusted attribution recorded consistently across one generated project."""

    workflow_author: str
    generated_at: str

    @classmethod
    def create(cls, author_name: Any, generated_at: Any = None) -> "ExportMetadata":
        author = " ".join(_text(author_name).split())[:200] or "AnnoBio user"
        timestamp = " ".join(_text(generated_at).split())[:64]
        if not timestamp:
            timestamp = datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")
        return cls(workflow_author=author, generated_at=timestamp)

    def python_header(self, subject: str) -> str:
        """Return a valid module docstring even when names contain quotes or newlines."""
        document = (
            f"{' '.join(_text(subject).split())}\n\n"
            f"Workflow author: {self.workflow_author}\n"
            "Generated by: AnnoBio\n"
            f"Exported at: {self.generated_at}\n"
        )
        escaped = document.replace("\\", "\\\\").replace('"""', '\\"""')
        return f'"""{escaped}"""\n'


def _text(value: Any) -> str:
    return str(value or "").strip()


def _slug(value: Any, fallback: str = "pipeline") -> str:
    result = re.sub(r"[^a-z0-9]+", "-", _text(value).lower()).strip("-")
    return result[:80] or fallback


def _identifier(value: Any, fallback: str) -> str:
    result = re.sub(r"\W+", "_", _text(value), flags=re.UNICODE).strip("_").lower()
    if not result or result[0].isdigit() or keyword.iskeyword(result):
        result = f"{fallback}_{result}" if result else fallback
    return result[:72]


def _python_literal(value: Any) -> str:
    return pprint.pformat(value, width=100, sort_dicts=False)


def _credential_config(
    run: dict[str, Any],
    credentials_by_id: dict[str, dict[str, Any]],
    default_credential_id: str,
    max_tokens: int,
) -> dict[str, Any]:
    credential_id = _text(run.get("runCredentialId")) or default_credential_id
    credential = credentials_by_id.get(credential_id) or {}
    provider = _text(credential.get("provider"))
    model = _text(credential.get("model") or credential.get("llm"))
    base_url = _text(credential.get("base_url"))
    return {
        "engine": "openrouter" if provider.lower() == "openrouter" else "litellm",
        "provider": provider,
        "model": model,
        "base_url": base_url,
        "max_tokens": max(256, int(max_tokens or 8192)),
    }


def _processor_module(node: dict[str, Any], metadata: ExportMetadata) -> tuple[str, str, dict[str, Any]]:
    """Render compiler-normalized Process source; validation belongs to the compiler."""
    name = _text(node.get("name")) or "Process"
    module = metadata.python_header(f'User-defined Process step: {name}.') + (
        "\n# Edit this function normally; main.py calls process(df).\n\n"
        + node["dfCode"] + "\n"
    )
    return name, "df", {"module": module}


def _prompt_module(
    name: str, compiled_config: dict[str, Any], model_config: dict[str, Any],
    metadata: ExportMetadata,
) -> tuple[str, dict[str, Any], str]:
    """Render the compiler's resolved Prompt configuration without interpreting canvas data."""
    sections = compiled_config["sections"]
    mapping = compiled_config["input_mapping"]
    input_types = compiled_config["input_types"]
    output_schema = compiled_config["output_schema"]
    concurrency = compiled_config["settings"]["run_concurrency"]

    module = (
        metadata.python_header(f'User-defined Prompt step: {name}.')
        + "\nfrom __future__ import annotations\n\n"
        + "from pathlib import Path\n\n"
        + "import pandas as pd\n\n"
        + "from engine.base import BaseEngine, run_prompt_step\n\n\n"
        + "# This configuration is the user's selected Prompt and Run, exported by AnnoBio.\n"
        + "# API keys are intentionally absent; set them in .env or the process environment.\n"
        + f"PROMPT_NAME = {_python_literal(name)}\n"
        + f"SECTIONS = {_python_literal(sections)}\n"
        + f"INPUT_MAPPING = {_python_literal(mapping)}\n"
        + f"INPUT_TYPES = {_python_literal(input_types)}\n"
        + f"OUTPUT_SCHEMA = {_python_literal(output_schema)}\n"
        + f"MODEL_CONFIG = {_python_literal(model_config)}\n"
        + f"DEFAULT_CONCURRENCY = {concurrency}\n\n\n"
        + "def run(\n"
        + "    frame: pd.DataFrame,\n"
        + "    engine: BaseEngine,\n"
        + "    *,\n"
        + "    input_root: Path,\n"
        + "    concurrency: int | None = None,\n"
        + "    model_override: str | None = None,\n"
        + ") -> pd.DataFrame:\n"
        + '    """Execute this Prompt once per input row and return its materialized Dataset."""\n'
        + "    model_config = dict(MODEL_CONFIG)\n"
        + "    if model_override:\n"
        + '        model_config["model"] = model_override\n'
        + "    return run_prompt_step(\n"
        + "        frame,\n"
        + "        engine,\n"
        + "        prompt_name=PROMPT_NAME,\n"
        + "        sections=SECTIONS,\n"
        + "        input_mapping=INPUT_MAPPING,\n"
        + "        input_types=INPUT_TYPES,\n"
        + "        output_schema=OUTPUT_SCHEMA,\n"
        + "        model_config=model_config,\n"
        + "        input_root=input_root,\n"
        + "        concurrency=DEFAULT_CONCURRENCY if concurrency is None else concurrency,\n"
        + "    )\n"
    )
    config = {
        "sections": sections,
        "input_mapping": mapping,
        "input_types": input_types,
        "output_schema": output_schema,
        "model": model_config,
    }
    return name, config, module


def _engine_base_module(metadata: ExportMetadata) -> str:
    return metadata.python_header("Shared LLM engine contract and Prompt execution helpers generated by AnnoBio.") + r'''
from __future__ import annotations

import base64
import json
import mimetypes
import re
from abc import ABC, abstractmethod
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Any

import pandas as pd


class BaseEngine(ABC):
    """Provider-neutral interface used by every generated Prompt module."""

    @abstractmethod
    def complete(
        self,
        *,
        content: str | list[dict[str, Any]],
        output_schema: dict[str, Any],
        model_config: dict[str, Any],
    ) -> dict[str, Any] | list[dict[str, Any]]:
        """Return one structured object, or a list when return_shape is table."""


def build_json_schema(output_schema: dict[str, Any]) -> dict[str, Any]:
    """Translate AnnoBio field types into the JSON Schema sent to an LLM provider."""
    type_map = {
        "str": {"type": "string"},
        "float": {"type": "number"},
        "list_str": {"type": "array", "items": {"type": "string"}},
        "list_float": {"type": "array", "items": {"type": "number"}},
    }
    properties: dict[str, Any] = {}
    required: list[str] = []
    for field in output_schema.get("fields") or []:
        key = str(field["key"])
        schema = dict(type_map.get(field.get("type"), type_map["str"]))
        if field.get("description"):
            schema["description"] = str(field["description"])
        if field.get("allow_none"):
            schema = {"anyOf": [schema, {"type": "null"}]}
        else:
            required.append(key)
        properties[key] = schema
    row_schema = {
        "type": "object",
        "properties": properties,
        "required": required,
        "additionalProperties": False,
    }
    if output_schema.get("return_shape") == "table":
        return {
            "type": "object",
            "properties": {"rows": {"type": "array", "items": row_schema}},
            "required": ["rows"],
            "additionalProperties": False,
        }
    return row_schema


def response_format(output_schema: dict[str, Any]) -> dict[str, Any]:
    return {
        "type": "json_schema",
        "json_schema": {
            "name": "annobio_output",
            "strict": True,
            "schema": build_json_schema(output_schema),
        },
    }


def json_instruction(output_schema: dict[str, Any]) -> str:
    shape = "JSON object containing a rows array" if output_schema.get("return_shape") == "table" else "JSON object"
    return (
        f"\n\nReturn only one valid {shape} matching this JSON Schema; do not use Markdown:\n"
        + json.dumps(build_json_schema(output_schema), ensure_ascii=False, indent=2)
    )


def parse_structured_content(
    value: Any,
    output_schema: dict[str, Any],
) -> dict[str, Any] | list[dict[str, Any]]:
    """Parse provider content and enforce the exported Prompt's field contract locally."""
    return_shape = str(output_schema.get("return_shape") or "single")
    if isinstance(value, (dict, list)):
        parsed = value
    else:
        text = str(value or "").strip()
        fenced = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", text, flags=re.IGNORECASE)
        if fenced:
            text = fenced.group(1).strip()
        try:
            parsed = json.loads(text)
        except json.JSONDecodeError:
            opening, closing = ("[", "]") if return_shape == "table" else ("{", "}")
            start, end = text.find(opening), text.rfind(closing)
            if start < 0 or end < start:
                raise ValueError("The model response did not contain valid JSON.")
            parsed = json.loads(text[start : end + 1])
    if return_shape == "table":
        if isinstance(parsed, dict) and isinstance(parsed.get("rows"), list):
            parsed = parsed["rows"]
        if not isinstance(parsed, list):
            raise TypeError("The model must return a JSON array for a table Prompt.")
        rows = parsed
    elif isinstance(parsed, dict):
        rows = [parsed]
    else:
        raise TypeError("The model must return a JSON object for a single-row Prompt.")

    fields = list(output_schema.get("fields") or [])
    allowed_keys = {str(field["key"]) for field in fields}
    validated: list[dict[str, Any]] = []
    for row_index, row in enumerate(rows, start=1):
        if not isinstance(row, dict):
            raise TypeError(f"Output row {row_index} must be a JSON object.")
        unexpected = sorted(str(key) for key in row if key not in allowed_keys)
        if unexpected:
            raise ValueError(f"Output row {row_index} contains unexpected fields: {', '.join(unexpected)}.")
        for field in fields:
            key = str(field["key"])
            if key not in row:
                if field.get("allow_none"):
                    row[key] = None
                    continue
                raise ValueError(f'Output row {row_index} is missing required field "{key}".')
            field_value = row[key]
            if field_value is None and field.get("allow_none"):
                continue
            field_type = str(field.get("type") or "str")
            valid = (
                (field_type == "str" and isinstance(field_value, str))
                or (field_type == "float" and isinstance(field_value, (int, float)) and not isinstance(field_value, bool))
                or (field_type == "list_str" and isinstance(field_value, list) and all(isinstance(item, str) for item in field_value))
                or (
                    field_type == "list_float"
                    and isinstance(field_value, list)
                    and all(isinstance(item, (int, float)) and not isinstance(item, bool) for item in field_value)
                )
            )
            if not valid:
                raise TypeError(f'Output field "{key}" in row {row_index} does not match type {field_type}.')
        validated.append(row)
    return validated if return_shape == "table" else validated[0]


def _paths_from_cell(value: Any) -> list[str]:
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return []
    if isinstance(value, list):
        return [str(item) for item in value if str(item).strip()]
    text = str(value).strip()
    if not text:
        return []
    if text.startswith("["):
        parsed = json.loads(text)
        if not isinstance(parsed, list):
            raise ValueError("File cells must contain a path or a JSON array of paths.")
        return [str(item) for item in parsed if str(item).strip()]
    return [text]


def _data_url(path: Path, expected_kind: str) -> str:
    if not path.is_file():
        raise FileNotFoundError(f"Input file does not exist: {path}")
    mime = mimetypes.guess_type(path.name)[0] or "application/octet-stream"
    if expected_kind == "pdf" and mime != "application/pdf":
        raise ValueError(f"Expected a PDF file: {path}")
    if expected_kind == "image" and not mime.startswith("image/"):
        raise ValueError(f"Expected an image file: {path}")
    return f"data:{mime};base64," + base64.b64encode(path.read_bytes()).decode("ascii")


def compile_prompt_content(
    template: str,
    values: dict[str, Any],
    input_types: dict[str, str],
    input_root: Path,
) -> str | list[dict[str, Any]]:
    """Substitute text placeholders and turn image/PDF paths into multimodal content blocks."""
    blocks: list[dict[str, Any]] = []
    attached: set[str] = set()

    def append_text(text: str) -> None:
        if not text:
            return
        if blocks and blocks[-1].get("type") == "text":
            blocks[-1]["text"] += text
        else:
            blocks.append({"type": "text", "text": text})

    end = 0
    pattern = re.compile(r"(?<!\{)\{([^{}]+)\}(?!\})")
    for match in pattern.finditer(str(template)):
        append_text(template[end : match.start()])
        name = match.group(1)
        if name not in values:
            append_text(match.group(0))
            end = match.end()
            continue
        input_type = input_types.get(name, "text")
        value = values[name]
        if input_type not in ("image", "pdf"):
            append_text("" if value is None or (isinstance(value, float) and pd.isna(value)) else str(value))
            end = match.end()
            continue
        paths = _paths_from_cell(value)
        if not paths:
            raise ValueError(f'Missing {input_type} input for "{name}".')
        append_text(f"\n[{input_type.title()} files: {name}]\n")
        if name not in attached:
            for raw_path in paths:
                path = Path(raw_path).expanduser()
                if not path.is_absolute():
                    path = (input_root / path).resolve()
                url = _data_url(path, input_type)
                if input_type == "image":
                    blocks.append({"type": "image_url", "image_url": {"url": url}})
                else:
                    blocks.append({
                        "type": "file",
                        "file": {"filename": path.name, "file_data": url, "format": "application/pdf"},
                    })
            attached.add(name)
        end = match.end()
    append_text(template[end:])
    if len(blocks) == 1 and blocks[0].get("type") == "text":
        return str(blocks[0].get("text") or "")
    return blocks


def run_prompt_step(
    frame: pd.DataFrame,
    engine: BaseEngine,
    *,
    prompt_name: str,
    sections: list[dict[str, Any]],
    input_mapping: dict[str, str],
    input_types: dict[str, str],
    output_schema: dict[str, Any],
    model_config: dict[str, Any],
    input_root: Path,
    concurrency: int,
) -> pd.DataFrame:
    """Execute a Prompt concurrently while preserving deterministic input/output row order."""
    template = "\n\n".join(str(section.get("content") or "").strip() for section in sections).strip()
    records = frame.where(pd.notna(frame), None).to_dict(orient="records")
    fields = list(output_schema.get("fields") or [])
    columns = ["Input: #", *[f"Input: {str(column).strip()}" for column in frame.columns], "Output: #"]
    columns.extend(f"Output: {field['display']}" for field in fields)
    if len(frame.index) == 0:
        return pd.DataFrame(columns=columns)

    # Empty canvas branches may have no schema at export time. Resolve their inputs against
    # the actual data, and fail before any model calls if the mapping is still unresolved.
    input_mapping = dict(input_mapping)
    placeholders = list(dict.fromkeys(re.findall(r"(?<!\{)\{([^{}]+)\}(?!\})", template)))
    for name in placeholders:
        if input_mapping.get(name):
            continue
        exact = [column for column in frame.columns if column == name]
        folded = [column for column in frame.columns if str(column).casefold() == name.casefold()]
        matches = exact if exact else folded
        if len(matches) == 1:
            input_mapping[name] = matches[0]
    missing = [name for name in placeholders if not input_mapping.get(name)]
    if missing:
        raise ValueError(
            f'Prompt "{prompt_name}" has data but needs input mappings for '
            + ", ".join("{" + name + "}" for name in missing)
            + ". Set INPUT_MAPPING in its exported prompt module."
        )
    unknown = [str(column) for column in input_mapping.values() if column not in frame.columns]
    if unknown:
        raise ValueError(f'Prompt "{prompt_name}" maps inputs to missing columns: ' + ", ".join(sorted(set(unknown))) + ".")

    if len(frame.columns) != len(set(frame.columns)):
        raise ValueError(f'Prompt "{prompt_name}" received duplicate input columns.')

    def run_one(item: tuple[int, dict[str, Any]]) -> tuple[int, list[dict[str, Any]], str | None]:
        index, row = item
        try:
            values = {name: row.get(column) for name, column in input_mapping.items()}
            content = compile_prompt_content(template, values, input_types, input_root)
            retries = max(0, min(5, int(model_config.get("max_retries") or 0)))
            for attempt in range(retries + 1):
                try:
                    result = engine.complete(content=content, output_schema=output_schema, model_config=model_config)
                    break
                except Exception:
                    if attempt == retries:
                        raise
            rows = result if isinstance(result, list) else [result]
            return index, [value for value in rows if isinstance(value, dict)], None
        except Exception as exc:  # Preserve long runs: one failed row must not discard successful rows.
            return index, [], str(exc)

    worker_count = max(1, min(32, int(concurrency or 1)))
    with ThreadPoolExecutor(max_workers=worker_count) as executor:
        outcomes = list(executor.map(run_one, enumerate(records)))

    materialized: list[dict[str, Any]] = []
    for input_index, output_rows, error in outcomes:
        row = records[input_index]
        rows = output_rows or ([{}] if error else [])
        for output in rows:
            record: dict[str, Any] = {"Input: #": input_index + 1}
            record.update({f"Input: {str(column).strip()}": row.get(column) for column in frame.columns})
            record["Output: #"] = len(materialized) + 1
            for field in fields:
                header = f"Output: {field['display']}"
                record[header] = error if error else output.get(field["key"], output.get(field["display"]))
            materialized.append(record)
        print(f"[{prompt_name}] {input_index + 1}/{len(records)}", flush=True)
    return pd.DataFrame(materialized, columns=columns)
'''


def _litellm_engine_module(metadata: ExportMetadata) -> str:
    return metadata.python_header("LiteLLM implementation of the generated AnnoBio engine contract.") + r'''
from __future__ import annotations

import os
from typing import Any

from litellm import completion

from .base import BaseEngine, json_instruction, parse_structured_content, response_format


class LiteLLMEngine(BaseEngine):
    """Call any LiteLLM-supported provider without embedding credentials in exported code."""

    def complete(
        self,
        *,
        content: str | list[dict[str, Any]],
        output_schema: dict[str, Any],
        model_config: dict[str, Any],
    ) -> dict[str, Any] | list[dict[str, Any]]:
        model = os.getenv("ANNOBIO_MODEL") or str(model_config.get("model") or "").strip()
        if not model:
            raise ValueError("No model is configured. Set ANNOBIO_MODEL in .env.")
        provider = str(model_config.get("provider") or "").strip().lower()
        if provider == "openrouter" and not model.startswith("openrouter/"):
            model = f"openrouter/{model}"
        api_key = os.getenv("ANNOBIO_API_KEY")
        if not api_key and provider == "openrouter":
            api_key = os.getenv("OPENROUTER_API_KEY")
        kwargs: dict[str, Any] = {
            "model": model,
            "messages": [{"role": "user", "content": content}],
            "max_tokens": int(model_config.get("max_tokens") or 8192),
            "response_format": response_format(output_schema),
        }
        # When ANNOBIO_API_KEY is blank, LiteLLM can use its normal provider-specific variables
        # such as OPENAI_API_KEY or ANTHROPIC_API_KEY.
        if api_key:
            kwargs["api_key"] = api_key
        base_url = os.getenv("ANNOBIO_BASE_URL") or str(model_config.get("base_url") or "").strip()
        if base_url:
            kwargs["api_base"] = base_url
        try:
            response = completion(**kwargs)
        except Exception as exc:
            message = str(exc).lower()
            if not any(token in message for token in ("response_format", "json_schema", "structured output", "not supported")):
                raise
            kwargs.pop("response_format", None)
            fallback = json_instruction(output_schema)
            if isinstance(content, str):
                kwargs["messages"] = [{"role": "user", "content": content + fallback}]
            else:
                kwargs["messages"] = [{"role": "user", "content": [*content, {"type": "text", "text": fallback}]}]
            response = completion(**kwargs)
        message = response.choices[0].message
        parsed = getattr(message, "parsed", None)
        raw = parsed if parsed is not None else getattr(message, "content", "")
        return parse_structured_content(raw, output_schema)
'''


def _openrouter_engine_module(metadata: ExportMetadata) -> str:
    return metadata.python_header("Direct OpenRouter implementation of the generated AnnoBio engine contract.") + r'''
from __future__ import annotations

import os
import time
from typing import Any

import httpx

from .base import BaseEngine, json_instruction, parse_structured_content, response_format


class OpenRouterEngine(BaseEngine):
    """Call OpenRouter's OpenAI-compatible chat-completions API directly."""

    def complete(
        self,
        *,
        content: str | list[dict[str, Any]],
        output_schema: dict[str, Any],
        model_config: dict[str, Any],
    ) -> dict[str, Any] | list[dict[str, Any]]:
        api_key = os.getenv("OPENROUTER_API_KEY") or os.getenv("ANNOBIO_API_KEY")
        if not api_key:
            raise ValueError("No OpenRouter key is configured. Set OPENROUTER_API_KEY in .env.")
        model = os.getenv("ANNOBIO_MODEL") or str(model_config.get("model") or "").strip()
        if model.startswith("openrouter/"):
            model = model.removeprefix("openrouter/")
        if not model:
            raise ValueError("No OpenRouter model is configured. Set ANNOBIO_MODEL in .env.")
        base_url = (os.getenv("OPENROUTER_BASE_URL") or "https://openrouter.ai/api/v1").rstrip("/")
        headers = {"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"}
        if os.getenv("OPENROUTER_HTTP_REFERER"):
            headers["HTTP-Referer"] = os.environ["OPENROUTER_HTTP_REFERER"]
        if os.getenv("OPENROUTER_APP_NAME"):
            headers["X-OpenRouter-Title"] = os.environ["OPENROUTER_APP_NAME"]
        payload: dict[str, Any] = {
            "model": model,
            "messages": [{"role": "user", "content": content}],
            "max_tokens": int(model_config.get("max_tokens") or 8192),
            "response_format": response_format(output_schema),
        }
        response = self._post(f"{base_url}/chat/completions", headers, payload)
        if response.status_code == 400 and any(
            token in response.text.lower() for token in ("response_format", "json_schema", "structured output", "not supported")
        ):
            payload.pop("response_format", None)
            fallback = json_instruction(output_schema)
            if isinstance(content, str):
                payload["messages"] = [{"role": "user", "content": content + fallback}]
            else:
                payload["messages"] = [{"role": "user", "content": [*content, {"type": "text", "text": fallback}]}]
            response = self._post(f"{base_url}/chat/completions", headers, payload)
        response.raise_for_status()
        raw = response.json()["choices"][0]["message"].get("content", "")
        return parse_structured_content(raw, output_schema)

    @staticmethod
    def _post(url: str, headers: dict[str, str], payload: dict[str, Any]) -> httpx.Response:
        last_response: httpx.Response | None = None
        last_error: httpx.HTTPError | None = None
        for attempt in range(4):
            try:
                response = httpx.post(url, headers=headers, json=payload, timeout=120.0)
            except (httpx.TimeoutException, httpx.NetworkError) as exc:
                last_error = exc
                if attempt < 3:
                    time.sleep(2**attempt)
                    continue
                raise
            last_response = response
            if response.status_code not in (429, 500, 502, 503, 504):
                return response
            if attempt < 3:
                retry_after = response.headers.get("Retry-After", "")
                try:
                    delay = min(60.0, max(0.0, float(retry_after)))
                except ValueError:
                    delay = float(2**attempt)
                time.sleep(delay)
        if last_response is None:
            raise RuntimeError("OpenRouter request failed before receiving a response.") from last_error
        return last_response
'''


