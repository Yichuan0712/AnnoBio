"""Build standalone Python projects from a selected AnnoBio pipeline route.

The generated archive deliberately contains code and data contracts only. Dataset rows, binary
assets, cached results, API keys, and canvas layout are never included.
"""

from __future__ import annotations

import io
import json
import keyword
import pprint
import re
import textwrap
import zipfile
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import PurePosixPath
from typing import Any


FORMAT_NAME = "annobio.pipeline"
FORMAT_VERSION = 1


class PipelineExportError(ValueError):
    """A user-correctable problem in the selected route or node configuration."""


@dataclass(frozen=True)
class ExportedFile:
    path: str
    content: str


@dataclass(frozen=True)
class ExportMetadata:
    """Trusted attribution recorded consistently across one generated project."""

    workflow_author: str
    generated_at: str

    @classmethod
    def create(cls, author_name: Any, generated_at: Any = None) -> "ExportMetadata":
        author = " ".join(_text(author_name).split())[:200] or "AnnoBio user"
        timestamp = " ".join(_text(generated_at).split())[:64]
        if not timestamp:
            timestamp = datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")
        return cls(workflow_author=author, generated_at=timestamp)

    def python_header(self, subject: str) -> str:
        """Return a valid module docstring even when names contain quotes or newlines."""
        document = (
            f"{' '.join(_text(subject).split())}\n\n"
            f"Workflow author: {self.workflow_author}\n"
            "Generated by: AnnoBio\n"
            f"Exported at: {self.generated_at}\n"
        )
        escaped = document.replace("\\", "\\\\").replace('"""', '\\"""')
        return f'"""{escaped}"""\n'


def _text(value: Any) -> str:
    return str(value or "").strip()


def _slug(value: Any, fallback: str = "pipeline") -> str:
    result = re.sub(r"[^a-z0-9]+", "-", _text(value).lower()).strip("-")
    return result[:80] or fallback


def _identifier(value: Any, fallback: str) -> str:
    result = re.sub(r"\W+", "_", _text(value), flags=re.UNICODE).strip("_").lower()
    if not result or result[0].isdigit() or keyword.iskeyword(result):
        result = f"{fallback}_{result}" if result else fallback
    return result[:72]


def _python_literal(value: Any) -> str:
    return pprint.pformat(value, width=100, sort_dicts=False)


def _parse_json_object(value: Any, label: str) -> dict[str, Any]:
    if value in (None, ""):
        return {}
    if isinstance(value, dict):
        return dict(value)
    try:
        parsed = json.loads(value)
    except (TypeError, json.JSONDecodeError) as exc:
        raise PipelineExportError(f"{label} is not valid JSON.") from exc
    if not isinstance(parsed, dict):
        raise PipelineExportError(f"{label} must be an object.")
    return parsed


def _extract_placeholders(sections: list[dict[str, Any]]) -> list[str]:
    template = "\n\n".join(_text(section.get("content")) for section in sections if _text(section.get("content")))
    found: list[str] = []
    for match in re.finditer(r"(?<!\{)\{([^{}]+)\}(?!\})", template):
        name = match.group(1)
        if name not in found:
            found.append(name)
    return found


def _sanitize_output_fields(raw_fields: list[Any]) -> list[dict[str, Any]]:
    fields: list[dict[str, Any]] = []
    used: set[str] = set()
    for raw in raw_fields:
        if not isinstance(raw, dict):
            continue
        display = _text(raw.get("key"))
        if not display:
            continue
        key_name = re.sub(r"\W", "_", display, flags=re.UNICODE).strip("_") or "field"
        if key_name[0].isdigit():
            key_name = f"field_{key_name}"
        candidate = key_name
        suffix = 1
        while candidate in used:
            candidate = f"{key_name}_{suffix}"
            suffix += 1
        used.add(candidate)
        field_type = _text(raw.get("type")).lower() or "str"
        if field_type not in {"str", "float", "list_str", "list_float"}:
            field_type = "str"
        fields.append(
            {
                "key": candidate,
                "display": display,
                "type": field_type,
                "description": str(raw.get("description") or ""),
                "examples": list(raw.get("examples") or []),
                "allow_none": raw.get("allowNone") is True or raw.get("allow_none") is True,
            }
        )
    return fields


def _prompt_output_schema(node: dict[str, Any]) -> dict[str, Any]:
    raw = node.get("outputFormat")
    if isinstance(raw, dict):
        return_shape = _text(raw.get("returnShape") or raw.get("return_shape")).lower()
        raw_fields = raw.get("fields") or []
    else:
        return_shape = _text(node.get("promptOutputReturnShape")).lower()
        try:
            raw_fields = json.loads(raw) if isinstance(raw, str) else (raw or [])
        except json.JSONDecodeError as exc:
            raise PipelineExportError(f'Prompt "{_text(node.get("name")) or "Prompt"}" has an invalid output schema.') from exc
    fields = _sanitize_output_fields(raw_fields if isinstance(raw_fields, list) else [])
    return {"return_shape": "table" if return_shape == "table" else "single", "fields": fields}


def _dataset_schema(node: dict[str, Any]) -> dict[str, Any]:
    content = node.get("datasetContent") or {}
    headers = [str(value) for value in (content.get("headers") or [])]
    raw_types = list(content.get("columnTypes") or [])
    columns = []
    for index, header in enumerate(headers):
        column_type = raw_types[index] if index < len(raw_types) else "text"
        if column_type not in ("text", "image", "pdf"):
            column_type = "text"
        columns.append({"name": header, "type": column_type})
    return {"sheet": "Input", "columns": columns}


def _normalize_route_item(raw: Any) -> dict[str, str]:
    if not isinstance(raw, dict):
        raise PipelineExportError("The selected route contains an invalid item.")
    item_type = _text(raw.get("type")).lower()
    if item_type == "dataset":
        node_id = _text(raw.get("dataset_node_id"))
        return {"type": item_type, "dataset_node_id": node_id}
    if item_type == "process":
        node_id = _text(raw.get("process_node_id"))
        return {"type": item_type, "process_node_id": node_id}
    if item_type == "prompt":
        return {
            "type": item_type,
            "prompt_node_id": _text(raw.get("prompt_node_id")),
            "run_node_id": _text(raw.get("run_node_id")),
        }
    raise PipelineExportError(f'Unsupported route item type: "{item_type or "unknown"}".')


def _require_node(nodes: dict[str, dict[str, Any]], node_id: str, expected_type: str) -> dict[str, Any]:
    node = nodes.get(node_id)
    if not node or node.get("type") != expected_type:
        raise PipelineExportError(f'The selected {expected_type} node "{node_id}" no longer exists.')
    return node


def _has_connection(connections: list[dict[str, Any]], edge_type: str, from_id: str, to_id: str) -> bool:
    return any(
        edge.get("type") == edge_type and edge.get("fromId") == from_id and edge.get("toId") == to_id
        for edge in connections
    )


def _validate_transition(
    previous: dict[str, str],
    current: dict[str, str],
    nodes: dict[str, dict[str, Any]],
    connections: list[dict[str, Any]],
) -> None:
    before, after = previous["type"], current["type"]
    if before == "dataset" and after == "process":
        if not _has_connection(connections, "dataset-to-process", previous["dataset_node_id"], current["process_node_id"]):
            raise PipelineExportError("The selected Dataset is no longer connected to the selected Process.")
        return
    if before == "process" and after == "dataset":
        if not _has_connection(connections, "process-to-dataset", previous["process_node_id"], current["dataset_node_id"]):
            raise PipelineExportError("The selected Process is no longer connected to the selected Dataset.")
        return
    if before == "dataset" and after == "prompt":
        run = _require_node(nodes, current["run_node_id"], "run")
        if _text(run.get("runWorkingSetId")) != previous["dataset_node_id"]:
            raise PipelineExportError("The selected Prompt Run no longer uses the preceding Dataset.")
        return
    if before == "prompt" and after == "dataset":
        dataset = _require_node(nodes, current["dataset_node_id"], "dataset")
        if _text(dataset.get("sourceRunNodeId")) != previous["run_node_id"]:
            raise PipelineExportError("The selected Dataset is no longer produced by the preceding Prompt Run.")
        return
    raise PipelineExportError(f"Unsupported route transition: {before} -> {after}.")


def _credential_config(
    run: dict[str, Any],
    credentials_by_id: dict[str, dict[str, Any]],
    default_credential_id: str,
    max_tokens: int,
) -> dict[str, Any]:
    credential_id = _text(run.get("runCredentialId")) or default_credential_id
    credential = credentials_by_id.get(credential_id) or {}
    provider = _text(credential.get("provider"))
    model = _text(credential.get("model") or credential.get("llm"))
    base_url = _text(credential.get("base_url"))
    return {
        "engine": "openrouter" if provider.lower() == "openrouter" else "litellm",
        "provider": provider,
        "model": model,
        "base_url": base_url,
        "max_tokens": max(256, int(max_tokens or 8192)),
    }


def _processor_module(node: dict[str, Any], metadata: ExportMetadata) -> tuple[str, str, dict[str, Any]]:
    name = _text(node.get("name")) or "Process"
    dataframe_code = _text(node.get("dfCode"))
    legacy_row_code = _text(node.get("code"))
    if dataframe_code:
        if not re.search(r"^\s*def\s+process\s*\(\s*df\b", dataframe_code, flags=re.MULTILINE):
            raise PipelineExportError(f'Process "{name}" must define process(df) before it can be exported.')
        code = dataframe_code
    elif re.search(r"^\s*def\s+process\s*\(\s*row\b", legacy_row_code, flags=re.MULTILINE):
        # Projects saved before the unified Process editor used process(row). Export a local
        # adapter so those projects retain their skip/error behavior but every generated step
        # now exposes the same process(df) contract.
        renamed = re.sub(
            r"^(\s*)def\s+process(\s*\(\s*row\b[^)]*\))",
            r"\1def _annobio_legacy_row_process\2",
            legacy_row_code,
            count=1,
            flags=re.MULTILINE,
        )
        code = (
            "# Migrated from this project's legacy process(row) function by AnnoBio.\n"
            "import pandas as pd\n\n"
            f"{renamed}\n\n"
            "def process(df):\n"
            "    \"\"\"Apply the legacy row transform through AnnoBio's dataframe contract.\"\"\"\n"
            "    output = []\n"
            "    records = df.where(pd.notna(df), None).to_dict(orient=\"records\")\n"
            "    for row in records:\n"
            "        try:\n"
            "            result = _annobio_legacy_row_process(dict(row))\n"
            "            if result is None:\n"
            "                continue\n"
            "            output.append(dict(result) if isinstance(result, dict) else {\"result\": result})\n"
            "        except Exception as exc:\n"
            "            output.append({\"error\": str(exc)})\n"
            "    return pd.DataFrame(output)\n"
        )
    else:
        raise PipelineExportError(f'Process "{name}" must define process(df) before it can be exported.')
    module = metadata.python_header(f'User-defined Process step: {name}.') + (
        "\n# The Process implementation below is preserved from the AnnoBio canvas.\n"
        "# Edit it normally; main.py calls process(df) for every Process step.\n\n"
        + code
        + "\n"
    )
    return name, "df", {"module": module}


def _prompt_module(
    prompt: dict[str, Any],
    run: dict[str, Any],
    model_config: dict[str, Any],
    available_columns: list[str],
    metadata: ExportMetadata,
) -> tuple[str, dict[str, Any], str]:
    name = _text(prompt.get("name")) or "Prompt"
    sections = prompt.get("sections") or []
    if not isinstance(sections, list) or not any(_text(section.get("content")) for section in sections if isinstance(section, dict)):
        raise PipelineExportError(f'Prompt "{name}" has no content.')
    sections = [
        {"name": str(section.get("name") or ""), "content": str(section.get("content") or "")}
        for section in sections
        if isinstance(section, dict)
    ]
    mapping = _parse_json_object(run.get("runInputToColumn"), f'Run input mapping for "{name}"')
    mapping = {_text(key): _text(value) for key, value in mapping.items() if _text(key)}
    input_types = prompt.get("inputTypes") or {}
    if not isinstance(input_types, dict):
        input_types = {}
    input_types = {str(key): str(value) for key, value in input_types.items()}
    placeholders = _extract_placeholders(sections)
    # Older Run nodes did not always persist an explicit mapping when a placeholder and its
    # Dataset column had the same name. Preserve that long-standing implicit behavior in exports
    # while keeping genuinely ambiguous inputs as validation errors.
    columns_by_folded_name: dict[str, list[str]] = {}
    for column in available_columns:
        if _text(column):
            columns_by_folded_name.setdefault(column.casefold(), []).append(column)
    for field in placeholders:
        if _text(mapping.get(field)):
            continue
        exact_matches = [column for column in available_columns if column == field]
        folded_matches = columns_by_folded_name.get(field.casefold(), [])
        if len(exact_matches) == 1:
            mapping[field] = exact_matches[0]
        elif len(folded_matches) == 1:
            mapping[field] = folded_matches[0]
    missing = [field for field in placeholders if not _text(mapping.get(field))]
    if missing:
        joined = ", ".join(f"{{{field}}}" for field in missing)
        run_name = _text(run.get("runName")) or "Run"
        raise PipelineExportError(
            f'Prompt "{name}" needs Dataset columns for {joined}. '
            f'Open "{run_name}" and map each input before exporting.'
        )
    output_schema = _prompt_output_schema(prompt)
    if not output_schema["fields"]:
        raise PipelineExportError(f'Prompt "{name}" must define at least one output field.')

    module = (
        metadata.python_header(f'User-defined Prompt step: {name}.')
        + "\nfrom __future__ import annotations\n\n"
        + "from pathlib import Path\n\n"
        + "import pandas as pd\n\n"
        + "from engine.base import BaseEngine, run_prompt_step\n\n\n"
        + "# This configuration is the user's selected Prompt and Run, exported by AnnoBio.\n"
        + "# API keys are intentionally absent; set them in .env or the process environment.\n"
        + f"PROMPT_NAME = {_python_literal(name)}\n"
        + f"SECTIONS = {_python_literal(sections)}\n"
        + f"INPUT_MAPPING = {_python_literal(mapping)}\n"
        + f"INPUT_TYPES = {_python_literal(input_types)}\n"
        + f"OUTPUT_SCHEMA = {_python_literal(output_schema)}\n"
        + f"MODEL_CONFIG = {_python_literal(model_config)}\n\n\n"
        + "def run(\n"
        + "    frame: pd.DataFrame,\n"
        + "    engine: BaseEngine,\n"
        + "    *,\n"
        + "    input_root: Path,\n"
        + "    concurrency: int,\n"
        + "    model_override: str | None = None,\n"
        + ") -> pd.DataFrame:\n"
        + '    """Execute this Prompt once per input row and return its materialized Dataset."""\n'
        + "    model_config = dict(MODEL_CONFIG)\n"
        + "    if model_override:\n"
        + '        model_config["model"] = model_override\n'
        + "    return run_prompt_step(\n"
        + "        frame,\n"
        + "        engine,\n"
        + "        prompt_name=PROMPT_NAME,\n"
        + "        sections=SECTIONS,\n"
        + "        input_mapping=INPUT_MAPPING,\n"
        + "        input_types=INPUT_TYPES,\n"
        + "        output_schema=OUTPUT_SCHEMA,\n"
        + "        model_config=model_config,\n"
        + "        input_root=input_root,\n"
        + "        concurrency=concurrency,\n"
        + "    )\n"
    )
    config = {
        "sections": sections,
        "input_mapping": mapping,
        "input_types": input_types,
        "output_schema": output_schema,
        "model": model_config,
    }
    return name, config, module


def _engine_base_module(metadata: ExportMetadata) -> str:
    return metadata.python_header("Shared LLM engine contract and Prompt execution helpers generated by AnnoBio.") + r'''
from __future__ import annotations

import base64
import json
import mimetypes
import re
from abc import ABC, abstractmethod
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Any

import pandas as pd


class BaseEngine(ABC):
    """Provider-neutral interface used by every generated Prompt module."""

    @abstractmethod
    def complete(
        self,
        *,
        content: str | list[dict[str, Any]],
        output_schema: dict[str, Any],
        model_config: dict[str, Any],
    ) -> dict[str, Any] | list[dict[str, Any]]:
        """Return one structured object, or a list when return_shape is table."""


def build_json_schema(output_schema: dict[str, Any]) -> dict[str, Any]:
    """Translate AnnoBio field types into the JSON Schema sent to an LLM provider."""
    type_map = {
        "str": {"type": "string"},
        "float": {"type": "number"},
        "list_str": {"type": "array", "items": {"type": "string"}},
        "list_float": {"type": "array", "items": {"type": "number"}},
    }
    properties: dict[str, Any] = {}
    required: list[str] = []
    for field in output_schema.get("fields") or []:
        key = str(field["key"])
        schema = dict(type_map.get(field.get("type"), type_map["str"]))
        if field.get("description"):
            schema["description"] = str(field["description"])
        if field.get("allow_none"):
            schema = {"anyOf": [schema, {"type": "null"}]}
        else:
            required.append(key)
        properties[key] = schema
    row_schema = {
        "type": "object",
        "properties": properties,
        "required": required,
        "additionalProperties": False,
    }
    if output_schema.get("return_shape") == "table":
        return {
            "type": "object",
            "properties": {"rows": {"type": "array", "items": row_schema}},
            "required": ["rows"],
            "additionalProperties": False,
        }
    return row_schema


def response_format(output_schema: dict[str, Any]) -> dict[str, Any]:
    return {
        "type": "json_schema",
        "json_schema": {
            "name": "annobio_output",
            "strict": True,
            "schema": build_json_schema(output_schema),
        },
    }


def json_instruction(output_schema: dict[str, Any]) -> str:
    shape = "JSON object containing a rows array" if output_schema.get("return_shape") == "table" else "JSON object"
    return (
        f"\n\nReturn only one valid {shape} matching this JSON Schema; do not use Markdown:\n"
        + json.dumps(build_json_schema(output_schema), ensure_ascii=False, indent=2)
    )


def parse_structured_content(
    value: Any,
    output_schema: dict[str, Any],
) -> dict[str, Any] | list[dict[str, Any]]:
    """Parse provider content and enforce the exported Prompt's field contract locally."""
    return_shape = str(output_schema.get("return_shape") or "single")
    if isinstance(value, (dict, list)):
        parsed = value
    else:
        text = str(value or "").strip()
        fenced = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", text, flags=re.IGNORECASE)
        if fenced:
            text = fenced.group(1).strip()
        try:
            parsed = json.loads(text)
        except json.JSONDecodeError:
            opening, closing = ("[", "]") if return_shape == "table" else ("{", "}")
            start, end = text.find(opening), text.rfind(closing)
            if start < 0 or end < start:
                raise ValueError("The model response did not contain valid JSON.")
            parsed = json.loads(text[start : end + 1])
    if return_shape == "table":
        if isinstance(parsed, dict) and isinstance(parsed.get("rows"), list):
            parsed = parsed["rows"]
        if not isinstance(parsed, list):
            raise TypeError("The model must return a JSON array for a table Prompt.")
        rows = parsed
    elif isinstance(parsed, dict):
        rows = [parsed]
    else:
        raise TypeError("The model must return a JSON object for a single-row Prompt.")

    fields = list(output_schema.get("fields") or [])
    allowed_keys = {str(field["key"]) for field in fields}
    validated: list[dict[str, Any]] = []
    for row_index, row in enumerate(rows, start=1):
        if not isinstance(row, dict):
            raise TypeError(f"Output row {row_index} must be a JSON object.")
        unexpected = sorted(str(key) for key in row if key not in allowed_keys)
        if unexpected:
            raise ValueError(f"Output row {row_index} contains unexpected fields: {', '.join(unexpected)}.")
        for field in fields:
            key = str(field["key"])
            if key not in row:
                if field.get("allow_none"):
                    row[key] = None
                    continue
                raise ValueError(f'Output row {row_index} is missing required field "{key}".')
            field_value = row[key]
            if field_value is None and field.get("allow_none"):
                continue
            field_type = str(field.get("type") or "str")
            valid = (
                (field_type == "str" and isinstance(field_value, str))
                or (field_type == "float" and isinstance(field_value, (int, float)) and not isinstance(field_value, bool))
                or (field_type == "list_str" and isinstance(field_value, list) and all(isinstance(item, str) for item in field_value))
                or (
                    field_type == "list_float"
                    and isinstance(field_value, list)
                    and all(isinstance(item, (int, float)) and not isinstance(item, bool) for item in field_value)
                )
            )
            if not valid:
                raise TypeError(f'Output field "{key}" in row {row_index} does not match type {field_type}.')
        validated.append(row)
    return validated if return_shape == "table" else validated[0]


def _paths_from_cell(value: Any) -> list[str]:
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return []
    if isinstance(value, list):
        return [str(item) for item in value if str(item).strip()]
    text = str(value).strip()
    if not text:
        return []
    if text.startswith("["):
        parsed = json.loads(text)
        if not isinstance(parsed, list):
            raise ValueError("File cells must contain a path or a JSON array of paths.")
        return [str(item) for item in parsed if str(item).strip()]
    return [text]


def _data_url(path: Path, expected_kind: str) -> str:
    if not path.is_file():
        raise FileNotFoundError(f"Input file does not exist: {path}")
    mime = mimetypes.guess_type(path.name)[0] or "application/octet-stream"
    if expected_kind == "pdf" and mime != "application/pdf":
        raise ValueError(f"Expected a PDF file: {path}")
    if expected_kind == "image" and not mime.startswith("image/"):
        raise ValueError(f"Expected an image file: {path}")
    return f"data:{mime};base64," + base64.b64encode(path.read_bytes()).decode("ascii")


def compile_prompt_content(
    template: str,
    values: dict[str, Any],
    input_types: dict[str, str],
    input_root: Path,
) -> str | list[dict[str, Any]]:
    """Substitute text placeholders and turn image/PDF paths into multimodal content blocks."""
    blocks: list[dict[str, Any]] = []
    attached: set[str] = set()

    def append_text(text: str) -> None:
        if not text:
            return
        if blocks and blocks[-1].get("type") == "text":
            blocks[-1]["text"] += text
        else:
            blocks.append({"type": "text", "text": text})

    end = 0
    pattern = re.compile(r"(?<!\{)\{([^{}]+)\}(?!\})")
    for match in pattern.finditer(str(template)):
        append_text(template[end : match.start()])
        name = match.group(1)
        if name not in values:
            append_text(match.group(0))
            end = match.end()
            continue
        input_type = input_types.get(name, "text")
        value = values[name]
        if input_type not in ("image", "pdf"):
            append_text("" if value is None or (isinstance(value, float) and pd.isna(value)) else str(value))
            end = match.end()
            continue
        paths = _paths_from_cell(value)
        if not paths:
            raise ValueError(f'Missing {input_type} input for "{name}".')
        append_text(f"\n[{input_type.title()} files: {name}]\n")
        if name not in attached:
            for raw_path in paths:
                path = Path(raw_path).expanduser()
                if not path.is_absolute():
                    path = (input_root / path).resolve()
                url = _data_url(path, input_type)
                if input_type == "image":
                    blocks.append({"type": "image_url", "image_url": {"url": url}})
                else:
                    blocks.append({
                        "type": "file",
                        "file": {"filename": path.name, "file_data": url, "format": "application/pdf"},
                    })
            attached.add(name)
        end = match.end()
    append_text(template[end:])
    if len(blocks) == 1 and blocks[0].get("type") == "text":
        return str(blocks[0].get("text") or "")
    return blocks


def run_prompt_step(
    frame: pd.DataFrame,
    engine: BaseEngine,
    *,
    prompt_name: str,
    sections: list[dict[str, Any]],
    input_mapping: dict[str, str],
    input_types: dict[str, str],
    output_schema: dict[str, Any],
    model_config: dict[str, Any],
    input_root: Path,
    concurrency: int,
) -> pd.DataFrame:
    """Execute a Prompt concurrently while preserving deterministic input/output row order."""
    template = "\n\n".join(str(section.get("content") or "").strip() for section in sections).strip()
    records = frame.where(pd.notna(frame), None).to_dict(orient="records")
    fields = list(output_schema.get("fields") or [])

    def run_one(item: tuple[int, dict[str, Any]]) -> tuple[int, list[dict[str, Any]], str | None]:
        index, row = item
        try:
            values = {name: row.get(column) for name, column in input_mapping.items()}
            content = compile_prompt_content(template, values, input_types, input_root)
            result = engine.complete(content=content, output_schema=output_schema, model_config=model_config)
            rows = result if isinstance(result, list) else [result]
            return index, [value for value in rows if isinstance(value, dict)], None
        except Exception as exc:  # Preserve long runs: one failed row must not discard successful rows.
            return index, [], str(exc)

    worker_count = max(1, min(32, int(concurrency or 1)))
    with ThreadPoolExecutor(max_workers=worker_count) as executor:
        outcomes = list(executor.map(run_one, enumerate(records)))

    materialized: list[dict[str, Any]] = []
    for input_index, output_rows, error in outcomes:
        row = records[input_index]
        rows = output_rows or ([{}] if error else [])
        for output in rows:
            record: dict[str, Any] = {"Input: #": input_index + 1}
            record.update({f"Input: {column}": row.get(column) for column in frame.columns})
            record["Output: #"] = len(materialized) + 1
            for field in fields:
                header = f"Output: {field['display']}"
                record[header] = error if error else output.get(field["key"], output.get(field["display"]))
            materialized.append(record)
        print(f"[{prompt_name}] {input_index + 1}/{len(records)}", flush=True)
    columns = ["Input: #", *[f"Input: {column}" for column in frame.columns], "Output: #"]
    columns.extend(f"Output: {field['display']}" for field in fields)
    return pd.DataFrame(materialized, columns=columns)
'''


