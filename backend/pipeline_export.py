def _without_llm(main_source: str) -> str:
    """Strip engine setup from a generated main.py whose route has no Prompt steps."""
    for line in _LLM_MAIN_LINES:
        if line not in main_source:
            raise AssertionError(f"Generated main.py no longer contains {line.strip()!r}.")
        main_source = main_source.replace(line, "")
    lines = main_source.splitlines(keepends=True)
    kept = [line for line in lines if not any(f"add_argument({option}" in line for option in _LLM_PARSER_OPTIONS)]
    if len(lines) - len(kept) != len(_LLM_PARSER_OPTIONS):
        raise AssertionError("Generated main.py parser options changed; update _without_llm.")
    return "".join(kept)


